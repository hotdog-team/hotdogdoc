-- 6. 주문 및 결제
CREATE TABLE orders (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    member_id NUMBER NOT NULL,
    address_id NUMBER,

    receiver_name VARCHAR2(100),
    receiver_phone VARCHAR2(50),

    delivery_address VARCHAR2(500),

    request_message VARCHAR2(500),

    total_amount NUMBER NOT NULL,
    delivery_fee NUMBER NOT NULL,

    payment_method VARCHAR2(50),

    status VARCHAR2(50) DEFAULT 'PENDING',

    tracking_number VARCHAR2(100),

    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    updated_at TIMESTAMP,

    CONSTRAINT fk_orders_member
        FOREIGN KEY (member_id)
        REFERENCES members(id),

    CONSTRAINT fk_orders_address
        FOREIGN KEY (address_id)
        REFERENCES addresses(id),

    CONSTRAINT chk_orders_status CHECK (
        status IN (
            'PENDING',
            'PROCESSING',
            'COMPLETED',
            'BEFORE_SHIPMENT',
            'IN_TRANSIT',
            'DELIVERED',
            'PARTIAL_CANCELLED',
            'CANCELLED',
            'PARTIAL_RETURN_REQUESTED',
            'RETURN_REQUESTED',
            'PARTIAL_RETURN_COMPLETED',
            'RETURN_COMPLETED'
        )
    ),

    CONSTRAINT chk_orders_payment_method CHECK (
        payment_method IN (
            'CASH',
            'CARD',
            'MOBILE_PAY'
        )
    )
);

