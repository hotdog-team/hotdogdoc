-- 4. 상품 및 메타 데이터
CREATE TABLE products (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category_id NUMBER,

    name VARCHAR2(255) NOT NULL,
    price NUMBER NOT NULL,
    discount_rate NUMBER DEFAULT 0 NOT NULL,
    delivery_fee NUMBER NOT NULL,

    stock_quantity NUMBER DEFAULT 0,

    short_description VARCHAR2(500),
    description CLOB,

    brand VARCHAR2(100),
    origin VARCHAR2(100),

    spec_info CLOB,

    alt_text CLOB,

    weight_score NUMBER DEFAULT 0,
    sales_count NUMBER DEFAULT 0,
    average_rate NUMBER DEFAULT 0 NOT NULL,
    review_count NUMBER DEFAULT 0 NOT NULL,

